// Regenerates src/data/ppeTraining.ts from the public repo's training log.
// Run: node scripts/import-ppe-log.mjs
import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/KennyUMN/ppe-compliance-ssl-yolov9/main/results/training-results.csv";
const COLUMNS = {
  epoch: "epoch",
  map50: "metrics/mAP50(B)",
  map5095: "metrics/mAP50-95(B)",
  precision: "metrics/precision(B)",
  recall: "metrics/recall(B)",
};

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`fetch ${SOURCE} failed: ${res.status}`);
const [header, ...lines] = (await res.text()).trim().split("\n");
const names = header.split(",");
const index = Object.fromEntries(
  Object.entries(COLUMNS).map(([key, col]) => {
    const i = names.indexOf(col);
    if (i < 0) throw new Error(`column ${col} missing from ${SOURCE}`);
    return [key, i];
  }),
);

const rows = lines.map((line) => {
  const cells = line.split(",");
  const row = Object.fromEntries(
    Object.entries(index).map(([key, i]) => [key, Number(cells[i])]),
  );
  if (Object.values(row).some(Number.isNaN)) throw new Error(`bad row: ${line}`);
  return row;
});

const body = rows
  .map((r) => `  { epoch: ${r.epoch}, map50: ${r.map50}, map5095: ${r.map5095}, precision: ${r.precision}, recall: ${r.recall} },`)
  .join("\n");

await writeFile(
  new URL("../src/data/ppeTraining.ts", import.meta.url),
  `// Generated by scripts/import-ppe-log.mjs from ${SOURCE}
// Do not edit by hand. Rerun the script after a new training run.

export interface EpochMetrics {
  epoch: number;
  map50: number;
  map5095: number;
  precision: number;
  recall: number;
}

export const ppeTraining: EpochMetrics[] = [
${body}
];
`,
);
console.log(`wrote ${rows.length} epochs`);
